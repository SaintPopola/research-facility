Visualiser.setTimerCallback(function()
{
    var k = 0;
    S.tick = S.tick + 1;
    var lg = Engine.getMasterPeakLevel(0);
    var rg = Engine.getMasterPeakLevel(1);
    var ln = clamp01(0.01 * (100.0 + Engine.getDecibelsForGainFactor(lg)) * 1.25 - 0.25);
    var rn = clamp01(0.01 * (100.0 + Engine.getDecibelsForGainFactor(rg)) * 1.25 - 0.25);
    S.lvlL = Math.max(ln, S.lvlL - 0.035);
    S.lvlR = Math.max(rn, S.lvlR - 0.035);
    var loud = (lg > 0.0005 || rg > 0.0005);
    if (loud) S.quiet = 0;
    else S.quiet = S.quiet + 1;

    S.orbPhase = S.orbPhase + 0.2 + 1.6 * Math.max(S.lvlL, S.lvlR);
    if (S.orbPhase >= 32.0) S.orbPhase = S.orbPhase - 32.0;
    S.orbFrame = Math.floor(S.orbPhase);
    var anyP = false;
    for (k = 0; k < NP; k++)
    {
        if (PL[k] > 0.0)
        {
            anyP = true;
            PX[k] = PX[k] + PVX[k];
            PY[k] = PY[k] + PVY[k];
            PVY[k] = PVY[k] * 0.985;
            PL[k] = PL[k] - 0.016;
        }
    }

    // full-rate when something is moving, 6 fps when idle (CPU)
    if (loud || anyP || (S.tick % 5 == 0))
    {
        this.repaint();
        MacroCard.repaint();
    }
    if (S.tick % 4 == 0)
    {
        S.voices = Math.max(0, Engine.getNumVoices());     // can read negative with a bypassed sampler
        S.cpu = Engine.getCpuUsage();
        Header.repaint();
    }
});
